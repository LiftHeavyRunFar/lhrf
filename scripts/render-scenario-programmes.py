ST={k:ParagraphStyle(k,fontName=f,fontSize=z,leading=l,textColor=colors.HexColor(c),spaceAfter=s,keepWithNext=k in ['title','h','sub']) for k,f,z,l,c,s in [
    ('title','Bold',25,30,'#11253C',14),('h','Bold',15,20,'#087FC4',10),('sub','Bold',11,15,'#11253C',7),
    ('body','Body',9.5,14,'#11253C',7),('small','Body',8,11,'#52667D',6),('cell','Body',8.5,11.5,'#11253C',0),('head','Bold',8.5,12,'#FFFFFF',0)]}
def p(s,style='body'):
    return Paragraph(escape(str(s)).replace('\n','<br/>'),ST[style])
def number(value):
    return format(value,'.3f').rstrip('0').rstrip('.') if isinstance(value,(int,float)) else str(value)
def table(headers,rows,widths):
    t=Table([[p(x,'head')for x in headers]]+[[p(x,'cell')for x in row]for row in rows],colWidths=widths,repeatRows=1,hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#11253C')),('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,colors.HexColor('#EEF4F9')]),('VALIGN',(0,0),(-1,-1),'TOP'),('TOPPADDING',(0,0),(-1,-1),6),('BOTTOMPADDING',(0,0),(-1,-1),6)]))
    return t
def build(path,story,title):
    def footer(c,d):
        c.setFont('Body',7.5);c.setFillColor(colors.HexColor('#52667D'))
        c.drawString(36,24,'LHRF / synthetic engine test / review copy')
        c.drawRightString(A4[0]-36,24,str(d.page))
        c.setStrokeColor(colors.HexColor('#087FC4'));c.line(36,A4[1]-28,A4[0]-36,A4[1]-28)
    SimpleDocTemplate(str(path),pagesize=A4,leftMargin=36,rightMargin=36,topMargin=44,bottomMargin=43,title=title,author='LHRF / engine output reviewed by Priya').build(story,onFirstPage=footer,onLaterPages=footer)
def programme(native,profile,path):
    c=native['config'];story=[p('LIFT HEAVY. RUN FAR.','small'),p('Scenario '+profile['id'],'title'),p(profile['label'],'h'),p('SHARED ENGINE OUTPUT / REVIEW COPY','sub'),p('Fictional athlete. Generated by the shared LHRF engine. This review copy is not approved for training. Prescriptions below come directly from the versioned engine. They are not manually rewritten.'),p('Starting point','h')]
    strength=profile['strength'];maxes=strength.get('reference_maxes_kg')
    strength_text=(' / '.join(k.capitalize()+' '+str(v)+' kg' for k,v in maxes.items()) if maxes else '; '.join(str(x['kg'])+' kg x '+str(x['reps'])+' '+x['lift']+' @ RPE '+str(x.get('rpe','not supplied')) for x in strength.get('sets',[])))
    availability=profile['availability'];caps=availability.get('visit_limits_minutes',availability.get('single_visit_limits_minutes',{}))
    race=profile['running'].get('race');history=profile['running'].get('weekly_km_history',[])
    running_text=('Recent weekly km: '+', '.join(map(str,history))+'. ' if history else 'Recent weekly mileage history was not supplied. ')+('Race baseline: '+str(race['distance_km'])+' km in '+str(race['seconds'])+' seconds.' if race else 'No race pace baseline supplied; health running stays time based.')
    story += [p(profile['priority']),p(strength_text or 'Strength loading evidence not supplied; calibrate working loads through warm-ups.'),p(running_text),p('Goal dates: '+', '.join(g['date'] for g in profile['goals'])),p('Your requirements','h'),p('Available: '+', '.join(d+' '+str(caps.get(d,'?'))+' min' for d in availability['days'])),p('Combined days: '+', '.join(availability.get('combined_run_lift_days',availability.get('separate_double_days',[])))),p('Important: visit caps, recovery history and priority handover may be unsupported. Read Priya\'s review alongside this output; any unconfirmed input remains a condition of the proposal.'),p('How to read the lifting tables','h'),p('Dose is sets x reps. Load is the engine suggestion in kg; "not set" means no load was supplied. Optional exercises remain labelled optional. RPE is the engine target. Warm-up and rest instructions are included only where the engine supplies them.'),p('Anticipated result','h'),p('No validated end-result forecast is supplied by this test. Targets in the input are aspirations. Passing structural checks would not establish an individual performance prediction.'),PageBreak(),p('Whole programme at a glance','title')]
    story.append(p('Reading scope: the first four weeks, event weeks, priority handovers and the peak long-run week are expanded below. The overview covers the full horizon. The accompanying raw archive retains every generated session and input.','small'))
    rows=[]
    for w in native['weeks']:
        runs=[r for s in w['sessions']for r in s.get('runs',[])]
        rows.append([w['week'],w['phase']+(' / '+w['runningPhase'] if w.get('runningPhase') else ''),', '.join(s['day'] for s in w['sessions']),round(sum(r.get('distanceKm',0) for r in runs),2),'Review' if w.get('reviewRequired') else 'No flag'])
    story += [table(['Week','Phase','Days','Run km*','Engine flag'],rows,[36,112,210,57,108]),p('*Includes race distance where the engine emits it. This is generated work, not completed training.','small')]
    expanded=set(range(1,5))
    for previous,current in zip(native['weeks'],native['weeks'][1:]):
        if previous.get('priority')!=current.get('priority'):expanded.update([previous['week'],current['week']])
    peak=max(native['weeks'],key=lambda w:max([r.get('distanceKm',0) for x in w['sessions']for r in x.get('runs',[]) if r.get('role')=='long-run'] or [0]))
    expanded.add(peak['week'])
    for w in native['weeks']:
        if w['week'] not in expanded and not any(s.get('eventDate') for s in w['sessions']):continue
        story += [PageBreak(),p('Week '+str(w['week']),'title'),p(w['phase'],'h')]
        if w.get('warnings'):
            story += [p('Engine warnings','sub')]+[p(x,'small') for x in w['warnings']]
        if w.get('unscheduled'):
            story += [p('Unscheduled work','sub'),p(json.dumps(w['unscheduled'],ensure_ascii=False),'small')]
        for s in w['sessions']:
            session_story=[]
            session_story += [p(s['day']+' / '+s.get('name','Session'),'h')]
            budget=s.get('timeBudget') or {}
            if not budget.get('event') and budget.get('totalMinutes') is not None:
                visits=budget.get('visits',[])
                session_story.append(p('Estimated whole visit: '+(' + '.join(str(v['totalMinutes'])+' min ('+str(v.get('capMinutes'))+' min window)' for v in visits) if visits else str(budget['totalMinutes'])+' min')+(' / separate visits, gap '+str(budget.get('minimumGapHours'))+' hours' if budget.get('separate') else '')+'. Warm-ups, rests and transitions included.','small'))
            if s.get('eventDate'):session_story.append(p('Event: '+s['eventDate']))
            for key in ['notes','note','description','desc']:
                if s.get(key):session_story.append(p(str(s[key]),'small'))
            if s.get('ex'):
                rows=[]
                for e in s['ex']:
                    meta=e[5] if len(e)>5 and isinstance(e[5],dict) else {}
                    label=e[0]+(' (optional)' if meta.get('optional')or meta.get('category')=='optional' else '')
                    rows.append([label,str(e[1])+' x '+str(e[2]),str(e[3]) if e[3] else 'not set',str(e[4]),meta.get('role','')])
                session_story += [table(['Exercise','Dose','kg','RPE','Role'],rows,[240,65,65,48,105]),Spacer(1,10)]
            for r in s.get('runs',[]):
                session_story += [p(r.get('name','Run'),'sub'),p(('Distance unmeasured' if r.get('distanceKnown') is False else number(r.get('distanceKm','?'))+' km')+' / '+str(r.get('minutes') if r.get('minutes') is not None else 'unknown')+' min / '+str(r.get('pace','')))]
                if r.get('steps'):
                    session_story.append(table(['Step','Distance / time','Pace / detail'],[[x.get('label','Step'),('distance unmeasured' if r.get('distanceKnown') is False else number(x.get('distanceKm',''))+' km')+(' / '+str(x['minutes'])+' min' if x.get('minutes') else ''),str(x.get('pace',''))+(' / '+str(x['detail']) if x.get('detail') else '')]for x in r['steps']],[185,92,246]))
                for key in ['coachNote','reason','structure']:
                    if r.get(key):session_story.append(p(r[key],'small'))
            for note in s.get('hybridNotes',[]):
                if note not in w.get('warnings',[]):session_story.append(p(note,'small'))
            for note in s.get('variationNotes',[]):session_story.append(p(note,'small'))
            session_story.append(Spacer(1,10))
            story.append(KeepTogether(session_story))
    build(path,story,'LHRF scenario '+profile['id']+' - native engine baseline')

def review(md,path):
    story=[];table_rows=[]
    def flush():
        if table_rows:
            headers=table_rows[0];rows=table_rows[1:];width=523/len(headers)
            story.append(table(headers,rows,[width]*len(headers)));story.append(Spacer(1,12));table_rows.clear()
    for line in md.splitlines():
        if line.startswith('|'):
            cells=[x.strip().replace('`','').replace('**','') for x in line.strip('|').split('|')]
            if not all(re.fullmatch(r'[: -]+',x or ' ')for x in cells):table_rows.append(cells)
            continue
        flush()
        line=line.replace('`','').replace('**','')
        if line.startswith('# '):story.append(p(line[2:],'title'))
        elif line.startswith('## '):story.append(p(line[3:],'h'))
        elif line.startswith('### '):story.append(p(line[4:],'sub'))
        elif line.strip():story.append(p(line))
    flush();build(path,story,'Priya - five scenario engine review')

