const assert=require('node:assert/strict');
const {reviewRunningRecovery}=require('../src/running-recovery-v2.js');
const {reviewWeek}=require('../src/weekly-review-v2.js');
const runs=[8,7,8].map(actualRPE=>({actualRPE,targetRPE:7}));
const input={runLogs:runs,readiness:{fatigue:2,legSoreness:1}};
const before=JSON.stringify(input);
const result=reviewRunningRecovery(input);
assert.equal(result.signal,'repeated-running-overshoot');
assert.equal(result.approvalRequired,true);
assert.equal(result.proposals[0].kind,'review-running-intensity');
assert.equal(JSON.stringify(input),before);
assert.equal(reviewRunningRecovery({runLogs:[{actualRPE:7,targetRPE:7}]}).approvalRequired,false);
assert.equal(reviewRunningRecovery({readiness:{fatigue:5,legSoreness:5}}).approvalRequired,false);
const combined=reviewWeek(input);
assert.equal(combined.running.signal,'repeated-running-overshoot');
assert.ok(combined.proposals.some(p=>p.kind==='review-running-intensity'));
assert.equal(combined.appliedChanges.length,0);
assert.equal(reviewWeek({}).approvalRequired,false);
console.log('PASS running feedback, readiness guard and combined weekly review');
